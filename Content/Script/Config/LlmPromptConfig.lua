## 第四部分：仇人的灾难计划

### 设计原则
1. **合理性**：在该场景下可行，符合仇人的能力
2. **复杂度**：不能太简单（一眼看穿），也不能太复杂（无法理解）
3. **线索性**：必须留下可调查的线索，给玩家破解机会
4. **戏剧性**：要有紧张感和冲击力
5. **幽默感**：即使是灾难，也要有一些荒诞或讽刺的元素

### 必须包含的要素

#### 1. 灾难类型与方式
- **具体手段**：用什么方法？（爆炸物/毒药/机关/系统破坏/其他）
- **作用范围**：影响哪些人？整个场景还是特定区域？
- **时间设定**：什么时候触发？为什么选择这个时间？

#### 2. 准备过程
- **资源获取**：仇人如何得到必要的材料/工具？
- **布置地点**：在哪里设置？如何避开他人视线？
- **测试与调整**：有没有预演或测试？

#### 3. 触发机制
- **触发条件**：时间触发/远程引爆/条件触发？
- **保险措施**：仇人如何确保不被提前发现？
- **后备计划**：如果主计划失败，有没有备用方案？

#### 4. 动机体现
- **为什么是这种方式**：体现仇人的性格和动机
- **象征意义**：这种灾难方式有什么隐喻？
- **内心矛盾**：计划中是否有犹豫或留下退路的痕迹？

