- **矛盾性**：他也有痛苦和犹豫，不是纯粹的恶
- **可救赎性**：留下说服的可能性

#### 执行力
- **智力水平**：要足够聪明，能设计复杂计划
- **资源能力**：能接触到什么资源来制造灾难
