- **主角（玩家）**：普通人，但有记忆保留能力
- **仇人**：关键角色，有复杂动机，既可恨又可怜
- **主要NPC（3-5人）**：与主角和仇人关系密切
- **次要NPC（2-3人）**：提供线索或推动剧情
- **功能型NPC（若干）**：点缀环境，增加真实感

### 每个角色必须包含

#### 1. 基础信息
- **姓名**：有意义的名字
- **年龄/身份**：符合场景
- **外貌特征**：1-2个记忆点
- **性格标签**：3-4个关键词

#### 2. 品质与状态
- **核心品质**：善良/邪恶/中立？优点和缺陷
- **当前状态**：心理状态、生活状况、压力源
- **能力特长**：擅长什么，在群体中的定位

#### 3. 记忆与背景
- **重要经历**：塑造性格的事件
- **秘密**：不为人知的一面
- **动机**：当前最想要的东西

#### 4. 关系定位
- **与主角的关系**：
  * 初始关系（陌生/朋友/敌对/暧昧）
  * 关系强度（1-10）
  * 关系历史（如何认识，有什么过往）
  
- **与仇人的关系**：
  * 仇人眼中的他/她（是利用对象/威胁/无关者）
